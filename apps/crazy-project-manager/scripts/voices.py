"""Build the bundled Mandarin clips using the studio's Edge TTS workflow."""

import asyncio
import hashlib
import json
import math
import pathlib
import random
import struct
import subprocess
import sys
import wave

import edge_tts

ROOT = pathlib.Path(__file__).resolve().parents[1]
DEST = ROOT / "dist/assets/voices/mandarin"
PROFILES = {
    "zhou": ("zh-CN-YunjianNeural", "-9%", "-13Hz"),
    "lin": ("zh-CN-XiaoxiaoNeural", "+5%", "-9Hz"),
    "tang": ("zh-CN-YunyangNeural", "+19%", "+14Hz"),
    "yi": ("zh-CN-YunxiNeural", "+10%", "+12Hz"),
}
DELIVERY = {
    ("zhou", "angry"): ("+1%", "-17Hz"),
    ("lin", "point"): ("+11%", "-10Hz"),
    ("tang", "excited"): ("+25%", "+20Hz"),
    ("yi", "lazy"): ("-19%", "-8Hz"),
    ("yi", "startled"): ("+23%", "+26Hz"),
    ("yi", "resume"): ("+16%", "+8Hz"),
}


def build_knock():
    """Mix two decaying wood resonances and a short transient at 24 kHz."""
    sample_rate = 24000
    rng = random.Random(120)
    previous_noise = 0
    samples = []
    for index in range(round(sample_rate * 0.23)):
        time = index / sample_rate
        noise = rng.uniform(-1, 1)
        crack = (noise - 0.74 * previous_noise) * 0.32 * math.exp(-time * 194)
        thud = math.sin(time * math.tau * (120 - time * 290)) * 0.63 * math.exp(-time * 25)
        wood = math.sin(time * math.tau * 260) * 0.2 * math.exp(-time * 64)
        value = max(-1, min(1, thud + wood + crack))
        samples.append(round(value * 32767))
        previous_noise = noise
    with wave.open(str(DEST / "knock.wav"), "wb") as stream:
        stream.setparams((1, 2, sample_rate, len(samples), "NONE", "not compressed"))
        stream.writeframes(struct.pack(f"<{len(samples)}h", *samples))


async def generate():
    DEST.mkdir(parents=True, exist_ok=True)
    data = subprocess.check_output(["node", str(ROOT / "scripts/voice-lines.mjs")], encoding="utf-8")
    lines = json.loads(data)
    sem = asyncio.Semaphore(4)

    async def generate_clip(role, mood, text):
        voice, rate, pitch = PROFILES[role]
        rate, pitch = DELIVERY.get((role, mood), (rate, pitch))
        key = "\0".join([role, mood, voice, rate, pitch, text])
        name = f"{role}-{hashlib.sha256(key.encode()).hexdigest()[:14]}.mp3"
        path = DEST / name
        async with sem:
            if not path.exists() or path.stat().st_size <= 1000:
                temporary = path.with_suffix(".part")
                for attempt in range(3):
                    try:
                        tts = edge_tts.Communicate(text, voice, rate=rate, pitch=pitch)
                        await asyncio.wait_for(tts.save(str(temporary)), 30)
                        if temporary.stat().st_size <= 1000:
                            raise ValueError(f"Empty clip for {name}")
                        temporary.replace(path)
                        print(name, path.stat().st_size, flush=True)
                        break
                    except Exception:
                        temporary.unlink(missing_ok=True)
                        if attempt == 2:
                            raise
                        await asyncio.sleep(0.8 + attempt)
        return [role, mood, text, f"/assets/voices/mandarin/{name}"]

    manifest = await asyncio.gather(*(generate_clip(*line) for line in lines))
    output = "// Generated by scripts/voices.py.\nexport const voiceClips = "
    output += json.dumps(manifest, ensure_ascii=False, indent=2) + ";\n"
    (ROOT / "dist/mandarin-voices.js").write_text(output, encoding="utf-8")
    build_knock()
    print(f"Prepared {len(manifest)} Mandarin clips.")


if __name__ == "__main__":
    if sys.platform == "win32":
        asyncio.set_event_loop_policy(asyncio.WindowsSelectorEventLoopPolicy())
    asyncio.run(generate())
